/** Zeichen, die kein eigenes Raster haben, werden zu diesem Block. */
const FALLBACK = ['###', '# #', '# #', '# #', '###'];

const ROWS = 5;

/**
 * Wandelt einen Text in fünf Zeilen Blockschrift.
 * @param {string} text
 * @returns {string[]} fünf Zeilen, direkt ausgabefertig
 */
export function toBanner(text) {
  const glyphs = [...String(text).toUpperCase()].map((char) => GLYPHS[char] ?? FALLBACK);

  return Array.from({ length: ROWS }, (_, row) =>
    glyphs
      .map((glyph) => glyph[row].replaceAll('#', '██').replaceAll(' ', '  '))
      .join('  ')
      .trimEnd(),
  );
}
